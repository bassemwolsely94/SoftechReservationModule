"""Print the «اعرض لي» product-tour coverage as Markdown: every module, its workflow
tours (desktop / mobile) and every screen with its tour length and continuation.
Regenerate the doc with:
    python manage.py help_tour_coverage > docs/architecture/29_PRODUCT_TOURS.md
"""
from django.core.management.base import BaseCommand

from apps.help import registry


class Command(BaseCommand):
    help = 'Markdown list of product-tour coverage (screens + workflow tours) per module.'

    def handle(self, *args, **opts):
        modules, screens = registry.load()
        with_tour = [k for k, s in screens.items() if s.get('tour')]
        flows = registry.flows(modules)
        steps = sum(len(s.get('tour') or []) for s in screens.values())
        w = self.stdout.write
        w('# 29 — Product tours («اعرض لي») coverage\n\n')
        w('Generated by `python manage.py help_tour_coverage` from `apps/help/content/` — do not edit by hand.\n\n')
        w(f'**{len(with_tour)} / {len(screens)} screens** have a tour ({steps} steps) · '
          f'**{len(flows)} workflow tours** '
          f'({sum(1 for f in flows.values() if f.get("mobile"))} mobile) · system tour: '
          f'{"yes" if "flow:general.system" in flows else "no"}.\n\n')
        w('`test_help` fails if any screen has no tour, if a step points at an element that no '
          'longer exists, or at a page / menu item that does not exist.\n')
        for m in modules.values():
            w(f"\n## {m.get('icon', '')} {m['title']['en']} — {m['title']['ar']}\n")
            mf = [f for f in flows.values() if f['module'] == m['key']]
            if mf:
                w('\n**Workflow tours**\n')
                for f in mf:
                    kind = '📱 mobile' if f.get('mobile') else '🖥️ desktop'
                    roles = ', '.join(f['roles']) if f.get('roles') else 'all roles'
                    w(f"- {f['title']['en']} / {f['title']['ar']} — {kind}, {len(f['steps'])} steps ({roles})\n")
            w('\n| Screen | Route | Tour steps | Continues into |\n|---|---|---|---|\n')
            for k in m['screens']:
                s = screens[k]
                n = len(s.get('tour') or [])
                cont = s.get('tour_continue') or ''
                w(f"| {s['title']['en']} — {s['title']['ar']} | `{s['routes'][0]}` | "
                  f"{n if n else '❌ none'} | {cont} |\n")
