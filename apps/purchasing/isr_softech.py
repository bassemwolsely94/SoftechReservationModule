"""
apps/purchasing/isr_softech.py — «طلبات التوريد / ISR» generated by SOFTECH's own rule.

Owner 2026-10-24: our ISR to Bab ElHadid (160) had about twice the lines and value of the
one SOFTECH made the same day (#26100661: 5,174 lines / 1.91M vs #26100662: 2,082 / 0.99M).
The engine gap (max(safety floor, rate × coverage) − the engine's stock snapshot) ordered
slow movers through the safety floor, used stock up to 3 days old and topped up to the
1.5-month maximum.

SOFTECH's rule, DECODED from its own ISRs to 160 (read-only, 2026-10-24):
  • itemqty        = ceil(rate × 0.8 month − stock) — fits 2,074/2,074 lines of #26100668 and
                     2,065/2,078 of #26100673 (the 13 = rates changed since). 0.8 month = the
                     «حد الطلب» the replenishment screen is run with. A line exists only when
                     stock < rate × 0.8 (the order point). Same for every creator (21 and 1509).
  • itemqty_cfarma = ceil(maximum − stock), maximum = stkbal.maxnowqty (rate × 1.5) — 2,078/2,078.
    Reference only: SOFTECH orders up to the ORDER POINT, not up to the maximum.
  • no HQ-stock condition (≈ 2,000 of its 2,078 lines were items HQ did not hold).

Our rule (owner: SOFTECH's rule + safeguards):
    target = rate × «حد الطلب» months (default 0.8 — as SOFTECH)        ← target 'order_point'
           | the maximum (stored maxnowqty, or rate × typed coverage)  ← target 'max'
    qty    = target − stock − in transit; under 0.16 pack → 0, else rounded UP (whole packs)
  • rate, maximum and stock read LIVE from server 100 — where SOFTECH builds its ISRs;
    transit = our in-transit transfers (SOFTECH does not deduct them);
  • only items HQ (100) holds at least one whole pack of, and qty capped at HQ's whole
    packs — both check options, OFF by default (owner 2026-10-24: an item HQ lacks today may be in
    stock by the time the request is filled, so it is never dropped unless asked);
  • filters like SOFTECH's «طلبيات الأصناف بناءا على حد الطلب» screen.

READ-ONLY: this module only reads. Writing stays in isr_writer (proposal → approve → push).
"""
