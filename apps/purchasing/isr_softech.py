def _bool(v, default):
    if v is None or v == '':
        return default
    if isinstance(v, bool):
        return v
    return str(v).strip().lower() in ('1', 'true', 'yes', 'on')


def _months(v, *, lo, hi, label, default=None):
    if v in (None, '', 0, '0'):
        return default
    try:
        m = float(v)
    except (TypeError, ValueError):
        raise ValueError(f'{label}: رقم غير صالح.')
    if not lo <= m <= hi:
        raise ValueError(f'{label}: يجب أن يكون بين {lo:g} و {hi:g} شهر.')
    return m


def rule_settings(data) -> dict:
    """Validate the screen's settings. Everything optional; defaults = SOFTECH's own ISR
    (HQ options off — owner 2026-10-24)."""
    data = data or {}
    st = {
        'target': str(data.get('target') or 'order_point'),
        'order_months': _months(data.get('order_months'), lo=0.1, hi=12, label='حد الطلب',
                                default=SOFTECH_ORDER_MONTHS),
        'coverage': _months(data.get('coverage_months'), lo=0.25, hi=12, label='التغطية'),
        'below_order_point': _bool(data.get('below_order_point'), False),
        'hq_only': _bool(data.get('hq_only'), False),
        'cap_hq': _bool(data.get('cap_hq'), False),
        'stock': str(data.get('stock') or 'all'),
        'origin': str(data.get('origin') or ''),
        'fridge': str(data.get('fridge') or ''),
        'name': str(data.get('name') or '').strip()[:100],
    }
    for k in TEXT_FILTERS:
        st[k] = str(data.get(k) or '').strip()[:20]
    if st['target'] not in TARGETS:
        raise ValueError('هدف الطلب غير صالح.')
    if st['stock'] not in STOCK_CHOICES:
        raise ValueError('فلتر رصيد الفرع غير صالح.')
    if st['origin'] not in ORIGIN_CHOICES:
        raise ValueError('فلتر المنشأ غير صالح.')
    if st['fridge'] not in FRIDGE_CHOICES:
        raise ValueError('فلتر الثلاجة غير صالح.')
    return st


def softech_need(target, stock, transit) -> int:
    """Whole packs: target − stock − transit; under 0.16 pack → 0, else rounded UP.
    Decimal from strings so 0.8 × 10 − 2 is never 6.0000000001 → 7."""
    raw = Decimal(str(round(float(target or 0) - float(stock or 0) - float(transit or 0), 4)))
    if raw < Decimal(str(MIN_PACK_FRACTION)):
        return 0
    return int(raw.to_integral_value(rounding=ROUND_CEILING))


def branch_max(rate, stored_max, coverage):
    """SOFTECH's stored maximum, or rate × the typed coverage (no sales → no maximum)."""
    if coverage is None:
        return float(stored_max or 0)
    rate = float(rate or 0)
    return round(rate * coverage, 4) if rate > 0 else 0.0


def target_qty(rate, stored_max, st):
    """What the branch is topped up to: rate × «حد الطلب» months (SOFTECH) or the maximum."""
    rate = float(rate or 0)
    if st['target'] == 'order_point':
        return round(rate * st['order_months'], 4) if rate > 0 else 0.0
    return branch_max(rate, stored_max, st['coverage'])


def _ceil_pos(x) -> float:
    """SOFTECH's itemqty_cfarma: ceil(maximum − stock), never negative."""
    d = Decimal(str(round(float(x), 4)))
    return float(max(Decimal(0), d.to_integral_value(rounding=ROUND_CEILING)))


def plan_lines(rows, hq, transit, items, st):
    """The pure rule. rows = {code: (stock, rate, stored_max)} for the branch; hq = {code:
    HQ real stock}; transit = {code: qty}; items = {code: item dict} (only orderable items
    that pass the item filters). Returns (lines, stats)."""
    stats = Counter()
    lines = []
    for code, (stock, rate, stored) in rows.items():
        stats['considered'] += 1
        it = items.get(code)
        if it is None:
            stats['not_orderable'] += 1
            continue
        stock, rate = float(stock or 0), float(rate or 0)
        if (st['stock'] == 'with' and stock <= 0) or (st['stock'] == 'zero' and stock > 0):
            stats['stock_filter'] += 1
            continue
        t = float(transit.get(code, 0) or 0)
        have = stock + t
        if st['target'] == 'max' and st['below_order_point'] and rate > 0 \
                and have >= rate * st['order_months']:
            stats['above_order_point'] += 1
            continue
        tgt = target_qty(rate, stored, st)
        mx = branch_max(rate, stored, st['coverage'])
        raw = tgt - have
        need = softech_need(tgt, stock, t)
        if need <= 0:
            stats['below_fraction' if raw > 0 else 'no_need'] += 1
            continue
        hq_whole = int(math.floor(max(0.0, float(hq.get(code, 0) or 0)) + 1e-9))
        if hq_whole < 1 and (st['hq_only'] or st['cap_hq']):
            stats['hq_none'] += 1
            continue
        qty, capped = need, False
        if st['cap_hq'] and qty > hq_whole:
            qty, capped = hq_whole, True
            stats['capped'] += 1
        lines.append({
            'itemcode': code, 'item_name': it['name'],
            'itemqty': qty,                                   # whole packs
            'itemqty_cfarma': _ceil_pos(mx - stock),          # as SOFTECH: ceil(maximum − stock)
            'nowqty': round(stock, 3),
            'itemsaleprice': it['price'], 'itemcostprice': it['cost'], 'suppcode': it['supplier'],
            'gap': round(raw, 2),
            # shown on the proposal (the writer ignores them)
            'rate': round(rate, 2), 'target': round(tgt, 2), 'max': round(mx, 2), 'transit': round(t, 2),
            'hq_stock': round(float(hq.get(code, 0) or 0), 2), 'need': need, 'capped': capped,
        })
    lines.sort(key=lambda ln: (-ln['need'] * ln['itemcostprice'], ln['itemcode']))
    stats['lines'] = len(lines)
    return lines, dict(stats)


