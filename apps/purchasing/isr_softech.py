def _read_softech(branch):
    """({code: (stock, rate, stored_max)}, {code: HQ real stock}, as_of) from server 100."""
    from config.sybase import get_sybase_connection
    from apps.purchasing.rate_writer import resolve_store
    bc = branch.softech_branch_id
    conn = get_sybase_connection()
    cur = conn.cursor()
    try:
        cur.execute('SELECT itemcode, nowqty, monthlyqty, maxnowqty FROM stkbal '
                    'WHERE branchcode = ? AND storecode = ? AND (maxnowqty > 0 OR monthlyqty > 0)',
                    [bc, resolve_store(branch)])
        rows = {str(r[0]).strip(): (float(r[1] or 0), float(r[2] or 0), float(r[3] or 0))
                for r in cur.fetchall()}
        cur.execute('SELECT s.itemcode, sum(s.nowqty) FROM stkbal s, stores st '
                    'WHERE s.storecode = st.storecode AND st.storerealbal = 1 AND s.branchcode = ? '
                    'GROUP BY s.itemcode', [HQ])
        hq = {str(r[0]).strip(): float(r[1] or 0) for r in cur.fetchall()}
        # how fresh server 100's copy of the branch is: its newest transaction there
        cur.execute('SELECT max(trans_time) FROM stktransm WHERE branchcode = ? AND docdate >= '
                    'dateadd(day, -2, convert(datetime, convert(char(8), getdate(), 112)))', [bc])
        row = cur.fetchone()
        last = row[0] if row else None
    finally:
        cur.close()
        conn.close()
    return rows, hq, (last.strftime('%Y-%m-%d %H:%M') if hasattr(last, 'strftime') else '')


def _items(codes, st):
    """{code: item dict} for orderable items passing the item filters (catalog, PG)."""
    from apps.catalog.models import Item
    from apps.catalog.wildcard import wq
    qs = (Item.objects.filter(softech_id__in=list(codes), is_stockable=True, pack_price__gt=0)
          .exclude(medicine_type='60')                       # customer gifts / coupons
          .exclude(supplier_trans__in=['2', '3']))           # return-only / إيقاف كامل
    field = {'supplier': 'supplier_code', 'producer': 'producer_code', 'medicine_type': 'medicine_type',
             'category': 'category__softech_id', 'family': 'family_code', 'store_classif': 'store_classif'}
    for k, f in field.items():
        if st.get(k):
            qs = qs.filter(**{f: st[k]})
    if st.get('origin'):
        qs = qs.filter(is_imported=(st['origin'] == 'imported'))
    if st.get('fridge'):
        qs = qs.filter(requires_fridge=(st['fridge'] == 'yes'))
    if st.get('name'):
        qs = qs.filter(wq(st['name'], 'name'))
    return {str(i.softech_id).strip(): {'name': i.name or '', 'price': float(i.pack_price or 0),
                                        'cost': float(i.cost_price or 0),
                                        'supplier': str(i.supplier_code or '').strip()}
            for i in qs.only('softech_id', 'name', 'pack_price', 'cost_price', 'supplier_code')}


def build_plan(branchcode, settings_data=None, *, max_lines=None):
    """Read SOFTECH (server 100) + catalog + transit and apply the rule. READ-ONLY."""
    from apps.branches.models import Branch
    from apps.purchasing.in_transit import by_branch_code
    st = rule_settings(settings_data)
    branch = Branch.objects.filter(softech_branch_id=str(branchcode)).first()
    if branch is None:
        raise ValueError(f'الفرع {branchcode} غير موجود.')
    if str(branchcode) == HQ:
        raise ValueError('طلب التوريد يكون لفرع، لا للرئيسي 100.')
    rows, hq, as_of = _read_softech(branch)
    items = _items(rows.keys(), st)
    transit, transit_days = by_branch_code(list(items), max_age=14)
    lines, stats = plan_lines(rows, hq, transit.get(str(branchcode), {}), items, st)
    if max_lines:
        lines = lines[:int(max_lines)]
    return {'branchcode': str(branchcode), 'rule': 'softech', 'settings': st, 'stats': stats,
            'as_of': as_of, 'transit_days': transit_days, 'lines': lines, 'line_count': len(lines),
            'coverage_months': st['coverage'] if st['target'] == 'max' else None}


def filter_options():
    """Choices for the screen's filters, from the catalog (code, label)."""
    from apps.catalog.models import Item
    base = Item.objects.filter(is_stockable=True, pack_price__gt=0)

    def pairs(code_f, *label_fs):
        seen = {}
        for row in base.exclude(**{code_f: ''}).exclude(**{f'{code_f}__isnull': True}) \
                .values_list(code_f, *label_fs).distinct():
            code = str(row[0]).strip()
            label = next((str(x).strip() for x in row[1:] if x and str(x).strip()), '')
            if code and code not in seen:
                seen[code] = label
        return sorted(([c, l] for c, l in seen.items()), key=lambda p: (p[1] or p[0]))

    return {
        'supplier': pairs('supplier_code', 'supplier_name'),
        'producer': pairs('producer_code', 'producer_name'),
        'medicine_type': pairs('medicine_type', 'medicine_type_name_ar', 'medicine_type_name'),
        'category': pairs('category__softech_id', 'category__name_ar', 'category__name'),
        'family': pairs('family_code', 'family_name_ar', 'family_name'),
        'store_classif': pairs('store_classif', 'store_classif_name'),
    }
