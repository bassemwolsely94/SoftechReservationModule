// W3: catalogue every hard-coded role check in src/ against the live role matrix.
// Writes docs/uat/role-checks-catalogue.md and one finding per check that is looser (P1) or
// stricter (P3) than the matrix. No browser: reads the code and .uat-expected.json only.
import fs from 'node:fs'
import path from 'node:path'
import { test, expect } from '@playwright/test'
import { expectedFor, can } from '../lib/expected.js'
import { finding } from '../lib/findings.js'
import { scanRoleChecks, verdictFor, ROLES } from './roleChecks.js'

const DOC = path.resolve(__dirname, '..', '..', '..', 'docs', 'uat', 'role-checks-catalogue.md')

// The table side, per role: the home user of that role (key = role name) in branch A.
const tableAllows = (role, perm) => {
  if (perm === 'branch:all') return role === 'admin' || !!expectedFor(role).allBranches
  const [module, action] = perm.split(':')
  return can(role, module, action)
}

const rolesText = r => (Array.isArray(r) ? (r.length ? r.join(', ') : '— nobody by role') : `every role except ${r.not.join(', ')}`)
const esc = s => String(s).replace(/\|/g, '\\|').replace(/`/g, "'")

test('catalogue of hard-coded role checks vs the role matrix', async () => {
  const hits = scanRoleChecks()
  expect(hits.length).toBeGreaterThan(50)            // the scanner still finds the checks
  const rows = hits.map(h => ({ ...h, ...verdictFor(h, tableAllows) }))

  for (const r of rows) {
    const where = r.route || `${r.file}:${r.line}`
    const base = { ws: 'W3', route: where, kind: 'button' }
    const note = `${r.file}:${r.line} ${r.kind}; inferred ${r.perm} (needs confirmation)${r.extra ? `; also opened by ${r.extra}` : ''}`
    if (r.looser.length) {
      finding({ ...base, key: r.looser.join(','), severity: 'P1',
        expected: `matrix denies ${r.perm} to ${r.looser.join(', ')}`,
        actual: `code lets ${r.looser.join(', ')} through — ${note}` })
    }
    if (r.stricter.length) {
      finding({ ...base, key: r.stricter.join(','), severity: 'P3',
        expected: `matrix allows ${r.perm} to ${r.stricter.join(', ')}`,
        actual: `code keeps ${r.stricter.join(', ')} out — ${note}` })
    }
    if (r.unknownRoles.length) {
      finding({ ...base, key: 'catalogue', kind: 'decision', severity: 'P3',
        expected: 'every role literal is a role in apps/users/roles.py',
        actual: `${r.file}:${r.line} names ${r.unknownRoles.join(', ')} — not a role (dead entry?)` })
    }
  }

  const count = v => rows.filter(r => r.verdict === v).length
  const md = [
    '# Hard-coded role checks in the frontend — catalogue (UAT W3)',
    '',
    `Generated by \`frontend/uat/buttons/roleCatalogue.spec.js\` from \`frontend/src/\` and the live role`,
    'matrix of the UAT copy (`.uat-expected.json`, one home user per role in branch A). Regenerate by',
    'running that spec; do not edit by hand.',
    '',
    '**Every "inferred" module:action is a guess — inferred — needs confirmation.** The verdict compares',
    'the roles the code lets through with the roles the matrix allows for that inferred permission:',
    '',
    '- **looser** — the code lets a role through that the matrix denies → finding **P1** (the server',
    '  may still refuse; the screen then shows a control that fails).',
    '- **stricter** — the matrix allows a role that the code keeps out → finding **P3**.',
    '- `branch:all` — the check opens other branches; compared with the role\'s all-branches flag.',
    '- *routing* — not a gate (where a role lands, or the generic admin bypass); no verdict.',
    '- *no-inference* — no module:action could be inferred; listed for the owner, no finding.',
    '- A menu item with `module:` also needs the matrix `view`; a `cap:` / `is_staff` switch can open',
    '  it for one user beyond the roles (noted, not counted).',
    '',
    `**${rows.length} role checks** — match ${count('match')}, looser ${count('looser')}, stricter ${count('stricter')}, ` +
      `both ${count('both')}, routing ${count('routing')}, no inference ${count('no-inference')}.`,
    '',
    '| # | file:line | kind | roles the code allows | inferred module:action | verdict | looser (P1) | stricter (P3) | note |',
    '|---|---|---|---|---|---|---|---|---|',
    ...rows.map((r, i) => `| ${i + 1} | \`${r.file}:${r.line}\` | ${r.kind} | ${esc(rolesText(r.roles))} | ` +
      `${r.perm ? `${r.perm} *(inferred — needs confirmation)*` : '—'} | ${r.verdict} | ${r.looser.join(', ')} | ` +
      `${r.stricter.join(', ')} | ${esc([r.why, r.extra && `also: ${r.extra}`, r.andModule && `AND matrix ${r.andModule}:view`,
        r.orMatrix && 'OR matrix', r.unknownRoles.length && `unknown role: ${r.unknownRoles.join(', ')}`].filter(Boolean).join('; '))} |`),
    '',
    `Roles compared: ${ROLES.join(', ')}.`,
    '',
  ].join('\n')
  fs.mkdirSync(path.dirname(DOC), { recursive: true })
  fs.writeFileSync(DOC, md)
  fs.mkdirSync(path.resolve(__dirname, '..', '..', 'test-results-uat'), { recursive: true })
  fs.writeFileSync(path.resolve(__dirname, '..', '..', 'test-results-uat', 'role-checks.json'), JSON.stringify(rows, null, 1))
  console.log(`[W3] ${rows.length} role checks catalogued → ${path.relative(process.cwd(), DOC)}`)
})
